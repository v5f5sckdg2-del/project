#слева направо
print(2 + 3 * 4) #14, потому что умножение имеет приоритет над сложением
print((10 / 2) * 3) #15.0, потому что деление и умножение имеют одинаковый приоритет и выполняются слева направо
print( 10 - 11 - 54) # -55, потому что вычитание выполняется слева направо

#справа налево
print(2 ** 3 ** 2) #512, потому что возведение в степень выполняется справа налево

#операторы сравнения

