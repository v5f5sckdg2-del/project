#Арифметические операции

#    + сложение                     5 + 5     
#    - вычитание                   10 - 3    
#     * умножение                   4 * 6     
#     / деление                    15 / 3    
#    // целочисленное деление      15 // 4
#    % остаток от деления          15 % 4
#   ** возведение в степень         2 ** 3

print(5 + 5, 10 - 3, 4 * 6, 15 / 3, 15 // 4, 15 % 4, 2 ** 3)

print(type( 6 / 3)) #float, потому что деление всегда возвращает float
print(type( 6 // 3)) #int, потому что целочисленное деление всегда возвращает int
print(type( 5 + 2.0)) #float, потому что при сложении int и float результат всегда float

print(-7 // 2) #-4, потому что целочисленное деление всегда округляет в меньшую сторону
print(-7 % 2) #1, потому что остаток от деления всегда положителен

# сокращенное присваивание
x = 10
x += 5 # x = x + 5
x -= 3 # x = x - 3
x *= 2 # x = x * 2
x //= 5 # x = x // 5
x **= 2 # x = x ** 2
x %=5 # x = x % 5
print(x) # 4, потому что 10 + 5 - 3 * 2 // 5 ** 2 % 5 = 4

